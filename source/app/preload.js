'use strict';
const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('posAPI', {
  isDesktop: true,
  db: (op, store, a, b) => ipcRenderer.invoke('db', op, store, a, b),
  firstRunData: () => ipcRenderer.invoke('firstRunData'),
  ordersQuery: q => ipcRenderer.invoke('ordersQuery', q),
  orderGet: id => ipcRenderer.invoke('orderGet', id),
  report: (a, b) => ipcRenderer.invoke('report', a, b),
  itemMonthly: sku => ipcRenderer.invoke('itemMonthly', sku),
  stats: () => ipcRenderer.invoke('stats'),
  historyState: () => ipcRenderer.invoke('historyState'),
  onHistory: cb => ipcRenderer.on('history', (e, s) => cb(s)),
  print: (html, css) => ipcRenderer.invoke('print', { html, css }),
  printDoc: o => ipcRenderer.invoke('printDoc', o),
  addPrinter: () => ipcRenderer.invoke('addPrinter'),
  showFile: f => ipcRenderer.invoke('showFile', f),
  saveInvoiceFile: o => ipcRenderer.invoke('saveInvoiceFile', o),
  openPath: f => ipcRenderer.invoke('openPath', f),
  savePdf: o => ipcRenderer.invoke('savePdf', o),
  rawPrint: bytes => ipcRenderer.invoke('rawPrint', bytes),
  comPorts: () => ipcRenderer.invoke('comPorts'),
  scannerState: () => ipcRenderer.invoke('scannerState'),
  restartScanner: () => ipcRenderer.invoke('restartScanner'),
  onScan: cb => ipcRenderer.on('scan', (e, c) => cb(c)),
  onScannerState: cb => ipcRenderer.on('scannerState', (e, s) => cb(s)),
  openDrawer: () => ipcRenderer.invoke('openDrawer'),
  printers: () => ipcRenderer.invoke('printers'),
  getConfig: () => ipcRenderer.invoke('getConfig'),
  setConfig: patch => ipcRenderer.invoke('setConfig', patch),
  backupNow: () => ipcRenderer.invoke('backupNow'),
  restoreDb: () => ipcRenderer.invoke('restoreDb'),
  chooseBackupDir: () => ipcRenderer.invoke('chooseBackupDir'),
  openFolder: which => ipcRenderer.invoke('openFolder', which),
  installUpdate: () => ipcRenderer.invoke('installUpdate'),
  checkUpdate: () => ipcRenderer.invoke('checkUpdate'),
  downloadUpdate: () => ipcRenderer.invoke('downloadUpdate'),
  onUpdateAvailable: cb => ipcRenderer.on('updateAvailable', (e, u) => cb(u)),
  undoUpdate: () => ipcRenderer.invoke('undoUpdate'),
  licenseState: () => ipcRenderer.invoke('licenseState'),
  setLicense: k => ipcRenderer.invoke('setLicense', k),
  loadLicenseFile: () => ipcRenderer.invoke('loadLicenseFile'),
  exitApp: () => ipcRenderer.invoke('exitApp')
});
